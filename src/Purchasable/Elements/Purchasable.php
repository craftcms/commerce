     *
     * @internal
     */
    public function loadSales(?Order $order = null): void
    {
        // Default the sales and salePrice to the original price without any sales
        $this->_sales = [];

        if ($this->getId()) {
            $this->_sales = app(Sales::class)->getSalesForPurchasable($this, $order);
            $this->_salesPrice = app(Sales::class)->getSalePriceForPurchasable($this, $order);
        }
    }
