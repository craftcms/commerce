    private function _currencyAttributeAsCurrency(string $attribute): string
    {
        $amount = $this->$attribute ?? 0;
        return Currency::formatAsCurrency($amount, $this->getStore()->getCurrency());
    }

    public function setAttributesFromRequest(array $values): void
    {
        $length = $values['length'] ?? null;
        unset($values['length']);
        if ($length !== null) {
            $this->length = $length ? (float)Localization::normalizeNumber($length) : null;
        }

        $width = $values['width'] ?? null;
        unset($values['width']);
        if ($width !== null) {
            $this->width = $width ? (float)Localization::normalizeNumber($width) : null;
        }

        $height = $values['height'] ?? null;
        unset($values['height']);
        if ($height !== null) {
            $this->height = $height ? (float)Localization::normalizeNumber($height) : null;
        }

        $weight = $values['weight'] ?? null;
        unset($values['weight']);
        if ($weight !== null) {
            $this->weight = $weight ? (float)Localization::normalizeNumber($weight) : null;
        }

        $this->setAttributes($values);
    }

    protected function inlineAttributeInputHtml(string $attribute): string
    {
        $localizePrice = function(string $attribute) {
            $price = $this->{$attribute};
            if (empty($this->getErrors($attribute))) {
                if ($price === null && $attribute === 'basePromotionalPrice') {
                    return null;
                } elseif ($price === null) {
                    $price = 0;
                }

                $price = I18N::getFormatter()->asDecimal($price);
            }

            return $price;
        };

        return match ($attribute) {
            'availableForPurchase' => PurchasableHelper::availableForPurchaseInputHtml($this->availableForPurchase),
            'price' => Currency::moneyInputHtml($localizePrice('basePrice'), [
                'id' => 'base-price',
                'name' => 'basePrice',
                'currency' => $this->getStore()->getCurrency()->getCode(),
                'currencyLabel' => $this->getStore()->getCurrency()->getCode(),
            ]),
            'promotionalPrice' => Currency::moneyInputHtml($localizePrice('basePromotionalPrice'), [
                'id' => 'base-promotional-price',
                'name' => 'basePromotionalPrice',
                'currency' => $this->getStore()->getCurrency()->getCode(),
                'currencyLabel' => $this->getStore()->getCurrency()->getCode(),
            ]),
            'sku' => PurchasableHelper::skuInputHtml($this->getSkuAsText()),
            default => parent::inlineAttributeInputHtml($attribute),
        };
    }

    public static function displayName(): string
    {
        $classNameParts = explode('\\', static::class);

        return array_pop($classNameParts);
    }

    private function getTeller(): Teller
    {
        return app(Currencies::class)->getTeller($this->getStore()->getCurrency());
    }

    public function __unset(string $name): void
    {
        // Allow clearing of specific memoized properties
        if (in_array($name, ['stock', 'shippingCategory', 'taxCategory'])) {
            $this->{'_' . $name} = null;
            return;
        }

        parent::__unset($name);
    }

    public function getStore(): Store
    {
        if ($this->_store === null || !in_array($this->siteId, $this->_store->getSites()->pluck('id')->all())) {
            if ($this->siteId === null) {
                throw new \RuntimeException('Purchasable::siteId cannot be null');
            }

            $this->_store = app(Stores::class)->getStoreBySiteId($this->siteId);
            if ($this->_store === null) {
                throw new \RuntimeException('Unable to retrieve store.');
            }
        }

        return $this->_store;
    }

    public function getStoreId(): int
    {
        return $this->getStore()->id;
    }

    public function getIsAvailable(): bool
    {
        // Is the element available for purchase?
        if (!$this->availableForPurchase) {
            return false;
        }

        // is the element enabled?
        if ($this->getStatus() !== self::STATUS_ENABLED) {
            return false;
        }

        // Temporary SKU can not be added to the cart
        if (PurchasableHelper::isTempSku($this->getSku())) {
            return false;
        }

        if (static::hasInventory() && $this->inventoryTracked && $this->getStock() < 1) {
            if (!app(Purchasables::class)->isPurchasableOutOfStockPurchasingAllowed($this)) {
                return false;
            }
        }

        return true;
    }

    public function setBasePrice(Money|array|float|int|null $basePrice): void
    {
        if (is_array($basePrice)) {
            if (isset($basePrice['value']) && $basePrice['value'] === '') {
                $this->_basePrice = null;
                return;
            }

            if (!isset($basePrice['currency'])) {
                $basePrice['currency'] = $this->getStore()->getCurrency();
            }

            $basePrice = MoneyHelper::toMoney($basePrice);
            // nullify if conversion fails
            $basePrice = $basePrice ?: null;
        }

        if ($basePrice instanceof Money) {
            $basePrice = MoneyHelper::toDecimal($basePrice);
        } elseif ($basePrice !== null) {
            $basePrice = (float)$basePrice;
        }

        $this->_basePrice = $basePrice;
    }

    public function getBasePrice(): ?float
    {
        return $this->_basePrice;
    }

    public function setBasePromotionalPrice(Money|array|float|int|null $basePromotionalPrice): void
    {
        if (is_array($basePromotionalPrice)) {
            if (isset($basePromotionalPrice['value']) && $basePromotionalPrice['value'] === '') {
                $this->_basePromotionalPrice = null;
                return;
            }

            if (!isset($basePromotionalPrice['currency'])) {
                $basePromotionalPrice['currency'] = $this->getStore()->getCurrency();
            }

            $basePromotionalPrice = MoneyHelper::toMoney($basePromotionalPrice);
            // nullify if conversion fails
            $basePromotionalPrice = $basePromotionalPrice ?: null;
        }

        if ($basePromotionalPrice instanceof Money) {
            $basePromotionalPrice = MoneyHelper::toDecimal($basePromotionalPrice);
        } elseif ($basePromotionalPrice !== null) {
            $basePromotionalPrice = (float)$basePromotionalPrice;
        }

        $this->_basePromotionalPrice = $basePromotionalPrice;
    }

    public function getBasePromotionalPrice(): ?float
    {
        return $this->_basePromotionalPrice;
    }

    public function setPrice(?float $price): void
    {
        $this->_price = $price;
    }

    public function getPrice(): ?float
    {
        if (!app(CatalogPricingRules::class)->canUseCatalogPricingRules()) {
            return $this->basePrice;
        }

        $price = $this->_price ?? $this->basePrice;

        return (float)$this->getTeller()->convertToString($price);
    }

    public function getPromotionalPrice(): ?float
    {
        $price = $this->getPrice();
        if (!app(CatalogPricingRules::class)->canUseCatalogPricingRules()) {
            // Use the sales system to figure out the price
            if (!isset($this->_sales)) {
                $this->loadSales();
            }
            $promotionalPrice = $this->_salesPrice ?? $this->basePromotionalPrice;
        } else {
            $promotionalPrice = $this->_promotionalPrice ?? $this->basePromotionalPrice;
        }

        if ($promotionalPrice === null) {
            return null;
        }

        $promotionalPrice = (float)$this->getTeller()->convertToString($promotionalPrice);
        return $this->getTeller()->lessThan($promotionalPrice, $price) ? $promotionalPrice : null;
    }

    public function setPromotionalPrice(?float $price): void
    {
        $this->_promotionalPrice = $price;
    }

    public function getCatalogPricingRule(): ?CatalogPricingRule
    {
        if ($this->_catalogPricingRule === null && $this->catalogPricingRuleId !== null) {
            $this->_catalogPricingRule = app(CatalogPricingRules::class)->getCatalogPricingRuleById($this->catalogPricingRuleId, $this->storeId);
        }

        return $this->_catalogPricingRule;
    }

    public function getSalePrice(): ?float
    {
        if ($this->_salePrice === null) {
            $this->_salePrice = $this->getPromotionalPrice() ?? $this->getPrice();
        }

        return $this->_salePrice ?? null;
    }

