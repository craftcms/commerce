            return collect();
        }

        return app(Inventory::class)->getInventoryLevelsForPurchasable($this);
    }

    /**
     * Update purchasable table.
     */
    public function afterSave(bool $isNew): void
    {
        $canonicalPurchasableId = $this->getCanonicalId();
        $purchasableId = $this->id;

        if (!$this->propagating) {
            $isOwnerDraftApplying = false;
            $isOwnerRevisionApplying = false;

            // If this is a nested element, check if the owner is a draft and is being applied
            if ($this instanceof NestedElementInterface) {
                $owner = $this->getOwner();
                // A draft is only being "applied" if the owner is the canonical of the draft.
                // Without this id check, "Save as a new product" from a draft would trip this branch
                // and steal the original variant's inventory item via the transfer logic below.
                $isOwnerDraftApplying = $owner
                    && $owner->getIsCanonical()
                    && $owner->duplicateOf !== null
                    && $owner->duplicateOf->getIsDraft()
                    && $owner->duplicateOf->getCanonicalId() === $owner->id;

                $isOwnerRevisionApplying = $owner
                    && $owner->duplicateOf !== null
                    && $owner->duplicateOf->getIsRevision()
                    && $owner->duplicateOf->getCanonicalId() === $owner->id;
            }

            if (!$this->getIsRevision()) {
                // Reset the purchasable's SKU when it is explicitly being duplicating
                if ($this->duplicateOf !== null && !$isOwnerDraftApplying && !$isOwnerRevisionApplying) {
                    $this->sku = PurchasableHelper::tempSku();
                    // Nullify inventory item so a new one is created
                    $this->inventoryItemId = null;
                }
            }

            $purchasable = PurchasableRecord::find($purchasableId);

            if (!$purchasable) {
                $purchasable = new PurchasableRecord();
            }
            $purchasable->sku = $this->getSku();
            $purchasable->id = $purchasableId;
            $purchasable->width = $this->width;
            $purchasable->height = $this->height;
            $purchasable->length = $this->length;
            $purchasable->weight = $this->weight;
            $purchasable->taxCategoryId = $this->taxCategoryId;

            // Only update the description for the primary site until we have a concept
            // of an order having a site ID
            if ($this->siteId == Sites::getPrimarySite()->id) {
                $purchasable->description = $this->getDescription();
            }

            $purchasable->save();

            // Always create the inventory item even if it's a temporary draft (in the slide) since we want to allow stock to be
            // added to inventory before it is saved as a permanent variant.
            if (static::hasInventory() && $canonicalPurchasableId) {
                /** @var InventoryItemRecord|null $inventoryItem */
                $inventoryItem = null;

                // When applying a draft to its canonical, hand the source's inventory
                // item over so any stock movements made on the draft persist.
                if ($isOwnerDraftApplying && $this->duplicateOf !== null) {
                    $inventoryItem = InventoryItemRecord::where('purchasableId', $this->duplicateOf->id)->first();
                    if ($inventoryItem && $inventoryItem->purchasableId != $canonicalPurchasableId) {
                        $inventoryItem->purchasableId = $canonicalPurchasableId;
                        if (!$inventoryItem->save()) {
                            // Could not transfer (e.g. canonical already has its own row); fall through to the find-or-create below.
                            $inventoryItem = null;
                        }
                    }
                }

                if (!$inventoryItem) {
                    $inventoryItem = app(Inventory::class)->ensureInventoryItemRecord($this);
                }

                if ($inventoryItem) {
                    $this->inventoryItemId = $inventoryItem->id;
                }
            }
        }

        if ($purchasableId) {
            // Set Purchasables stores data
            $purchasableStoreRecord = PurchasableStore::where('purchasableId', $purchasableId)
                ->where('storeId', $this->getStoreId())
                ->first();
            if (!$purchasableStoreRecord) {
                $purchasableStoreRecord = new PurchasableStore();
                $purchasableStoreRecord->storeId = $this->getStore()->id;

                if ($this->propagating) {
                    $purchasableStoreRecord->basePrice = 0;
                    $purchasableStoreRecord->basePromotionalPrice = null;
                    $purchasableStoreRecord->stock = app(Inventory::class)->getInventoryLevelsForPurchasable($this)->sum('availableTotal');
                    $purchasableStoreRecord->inventoryTracked = false;
                    $purchasableStoreRecord->allowOutOfStockPurchases = false;
                    $purchasableStoreRecord->minQty = null;
                    $purchasableStoreRecord->maxQty = null;
                    $purchasableStoreRecord->promotable = false;
                    $purchasableStoreRecord->availableForPurchase = false;
                    $purchasableStoreRecord->freeShipping = false;
                    $purchasableStoreRecord->purchasableId = $purchasableId;
                    $purchasableStoreRecord->shippingCategoryId = app(ShippingCategories::class)->getDefaultShippingCategory($this->getStore()->id)->id;

                    if ($this->duplicateOf !== null) {
                        // If this is a duplicate, copy the values from the original purchasable stores record
                        $purchasableStoreRecordDuplicate = PurchasableStore::where('purchasableId', $this->duplicateOf->id)
                            ->where('storeId', $this->getStoreId())
                            ->first();

                        if ($purchasableStoreRecordDuplicate) {
                            $purchasableStoreRecord->basePrice = $purchasableStoreRecordDuplicate->basePrice;
                            $purchasableStoreRecord->basePromotionalPrice = $purchasableStoreRecordDuplicate->basePromotionalPrice;
                            $purchasableStoreRecord->stock = app(Inventory::class)->getInventoryLevelsForPurchasable($this)->sum('availableTotal');
                            $purchasableStoreRecord->inventoryTracked = $purchasableStoreRecordDuplicate->inventoryTracked;
                            $purchasableStoreRecord->allowOutOfStockPurchases = $purchasableStoreRecordDuplicate->allowOutOfStockPurchases;
                            $purchasableStoreRecord->minQty = $purchasableStoreRecordDuplicate->minQty;
                            $purchasableStoreRecord->maxQty = $purchasableStoreRecordDuplicate->maxQty;
                            $purchasableStoreRecord->promotable = $purchasableStoreRecordDuplicate->promotable;
                            $purchasableStoreRecord->availableForPurchase = $purchasableStoreRecordDuplicate->availableForPurchase;
                            $purchasableStoreRecord->freeShipping = $purchasableStoreRecordDuplicate->freeShipping;
                            $purchasableStoreRecord->shippingCategoryId = $purchasableStoreRecordDuplicate->shippingCategoryId;
                        }
                    }
                }
            }

            if (!$this->propagating) {
                $purchasableStoreRecord->basePrice = $this->basePrice;
                $purchasableStoreRecord->basePromotionalPrice = $this->basePromotionalPrice;
                $purchasableStoreRecord->stock = app(Inventory::class)->getInventoryLevelsForPurchasable($this)->sum('availableTotal');
                $purchasableStoreRecord->inventoryTracked = $this::hasInventory() ? $this->inventoryTracked : false;
                $purchasableStoreRecord->allowOutOfStockPurchases = $this->allowOutOfStockPurchases;
                $purchasableStoreRecord->minQty = $this->minQty;
                $purchasableStoreRecord->maxQty = $this->maxQty;
                $purchasableStoreRecord->promotable = $this->promotable;
                $purchasableStoreRecord->availableForPurchase = $this->availableForPurchase;
                $purchasableStoreRecord->freeShipping = $this->freeShipping;
                $purchasableStoreRecord->purchasableId = $purchasableId;
                $purchasableStoreRecord->shippingCategoryId = $this->getShippingCategoryId();
            }

            $purchasableStoreRecord->save();
        }

        parent::afterSave($isNew);
    }

    public function afterPropagate(bool $isNew): void
    {
        parent::afterPropagate($isNew);

        if (!$this->getIsDraft() && !$this->getIsRevision()) {
            app(CatalogPricing::class)->createCatalogPricingJob([
                'purchasableIds' => [$this->getCanonicalId()],
                'storeId' => $this->getStoreId(),
            ]);
        }
    }

