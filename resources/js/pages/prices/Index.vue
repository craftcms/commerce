<script setup lang="ts">
  import {computed, h, onBeforeUnmount, onMounted, ref} from 'vue';
  import {
    ActionMenu,
    AdminTable,
    createCraftColumnHelper,
    SearchForm,
    useCraftTable,
    type ActionItemLink,
    type PaginationData,
  } from '@craftcms/cp';

  interface PriceRow {
    id: string;
    purchasable: {title: string; url: string | null; status: string} | null;
    rule: {name: string; url: string} | null;
    source: string | null;
    price: string;
    isPromotional: boolean;
  }

  const props = defineProps<{
    url: string;
    prices: PriceRow[];
    pagination: PaginationData;
    searchTerm: string | null;
    condition: Record<string, unknown>;
    conditionBuilder: unknown;
    conditionRuleCount: number;
    jobsRunning: boolean;
    sites: Array<ActionItemLink & {selected: boolean}>;
  }>();

  const t = (message: string) => window.Craft.t('commerce', message);
  const tApp = (message: string) => window.Craft.t('app', message);

  const searchTerm = ref(props.searchTerm ?? '');
  const showFilters = ref(false);
  let pendingCondition: Record<string, unknown> | null = null;

  /** The page URL with the current filter applied, which paging and search keep. */
  const pageUrl = computed(() => {
    const url = new URL(props.url, window.location.href);

    if (props.conditionRuleCount) {
      url.searchParams.set('condition', JSON.stringify(props.condition));
    }

    return url.toString();
  });

  const currentSite = computed(() => props.sites.find((site) => site.selected));

  const columnHelper = createCraftColumnHelper<PriceRow>();
  const columns = columnHelper.columns([
    columnHelper.accessor('purchasable', {
      header: t('Name'),
      meta: {trackSize: '2fr'},
      cell: ({getValue}) => {
        const purchasable = getValue();

        if (!purchasable) {
          return null;
        }

        return h('span', {class: 'commerce-price-purchasable'}, [
          h('craft-status', {status: purchasable.status}),
          purchasable.url
            ? h('a', {href: purchasable.url}, purchasable.title)
            : purchasable.title,
        ]);
      },
    }),
    columnHelper.accessor('rule', {
      header: t('Catalog Pricing Rule'),
      meta: {trackSize: '2fr'},
      cell: ({getValue, row}) => {
        const rule = getValue();

        return rule
          ? h('a', {href: rule.url}, rule.name)
          : h('span', {class: 'light'}, row.original.source ?? '');
      },
    }),
    columnHelper.accessor('price', {
      header: t('Price'),
      cell: ({getValue, row}) =>
        h(
          'span',
          {class: {'commerce-promotional-price': row.original.isPromotional}},
          getValue()
        ),
    }),
  ]);

  const table = useCraftTable<PriceRow>({
    get data() {
      return props.prices;
    },
    columns,
    getRowId: (row) => row.id,
    inertia: {
      url: pageUrl.value,
      pagination: () => props.pagination,
      dataProp: 'prices',
    },
  });

  function visit(condition: Record<string, unknown> | null): void {
    const url = new URL(props.url, window.location.href);

    if (condition) {
      url.searchParams.set('condition', JSON.stringify(condition));
    }

    if (searchTerm.value) {
      url.searchParams.set('search', searchTerm.value);
    }

    window.Cp.$router.visit(url.toString(), {preserveScroll: true});
  }

  function onConditionChange(event: Event): void {
    pendingCondition = (event as CustomEvent<{value: Record<string, unknown>}>)
      .detail.value;
  }

  function applyFilters(): void {
    showFilters.value = false;
    visit(pendingCondition ?? props.condition);
  }

  function clearFilters(): void {
    showFilters.value = false;
    pendingCondition = null;
    visit(null);
  }

  function refresh(): void {
    window.Cp.$router.reload({only: ['prices', 'pagination', 'jobsRunning']});
  }

  // Catalog prices are generated by queue jobs, so keep an eye on whether they're running.
  let poll: ReturnType<typeof setInterval> | undefined;
  onMounted(() => {
    poll = setInterval(
      () => window.Cp.$router.reload({only: ['jobsRunning']}),
      20000
    );
  });
  onBeforeUnmount(() => clearInterval(poll));
</script>

<template>
  <div class="commerce-prices">
    <div class="commerce-prices-toolbar">
      <ActionMenu
        v-if="sites.length > 1"
        icon="world"
        :label="currentSite?.label ?? null"
        :actions="sites"
      />
      <craft-button
        type="button"
        icon="filter"
        :variant="conditionRuleCount ? 'primary' : undefined"
        :aria-expanded="showFilters ? 'true' : 'false'"
        @click="showFilters = !showFilters"
        >{{
          conditionRuleCount
            ? `${tApp('Filter')} (${conditionRuleCount})`
            : tApp('Filter')
        }}</craft-button
      >
      <craft-callout
        v-if="jobsRunning"
        variant="warning"
        class="commerce-prices-jobs"
        :title="t('Data shown might be outdated.')"
        >{{ t('Pricing jobs are currently running.') }}</craft-callout
      >
      <craft-button
        type="button"
        icon="arrows-rotate"
        :aria-label="tApp('Refresh')"
        @click="refresh"
      ></craft-button>
    </div>

    <craft-pane
      v-if="showFilters"
      appearance="raised"
      padding="lg"
      class="commerce-prices-filters"
    >
      <craft-condition-builder
        :data-payload="JSON.stringify(conditionBuilder)"
        data-name="condition"
        @condition-builder-change="onConditionChange"
      ></craft-condition-builder>
      <div class="commerce-prices-filter-actions">
        <craft-button type="button" @click="clearFilters">{{
          conditionRuleCount ? tApp('Clear') : tApp('Cancel')
        }}</craft-button>
        <craft-button type="button" variant="primary" @click="applyFilters">{{
          tApp('Apply')
        }}</craft-button>
      </div>
    </craft-pane>

    <AdminTable
      :table="table"
      :title="t('Prices')"
      :from="pagination.from"
      :to="pagination.to"
      :total="pagination.total"
      :empty-message="t('No prices exist yet.')"
      enable-adjust-page-size
    >
      <template #table-header>
        <SearchForm
          :action="pageUrl"
          v-model="searchTerm"
          :options="{only: ['prices', 'pagination', 'searchTerm']}"
        />
      </template>
    </AdminTable>
  </div>
</template>

